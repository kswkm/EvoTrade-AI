from fastapi import APIRouter
from pydantic import BaseModel, Field

from app.schemas.trading import Signal
from app.services.paper_trading import PaperTradingService

router = APIRouter(prefix="/api/v1")


class PaperOrderRequest(BaseModel):
    symbol: str = Field(..., min_length=1, max_length=16)
    direction: str = Field(default="buy")
    quantity: int = Field(default=1, ge=1)
    price: float = Field(default=100.0, gt=0)
    strategy_version: str = Field(default="v1")


@router.get("/paper/account")
def get_paper_account() -> dict[str, object]:
    service = PaperTradingService()
    account = service.get_account_snapshot()
    return {
        "cash": account.cash,
        "equity": account.equity,
        "emergency_stop": account.emergency_stop,
        "daily_loss_pct": account.daily_loss_pct,
        "positions": account.current_positions,
    }


@router.post("/paper/order")
def submit_paper_order(payload: PaperOrderRequest) -> dict[str, object]:
    service = PaperTradingService()
    signal = Signal(
        symbol=payload.symbol,
        direction=payload.direction,
        confidence=0.8,
        rationale="Paper trading order generated by risk-validated service",
    )
    return service.submit_order_from_signal(signal, payload.quantity, payload.price, payload.strategy_version)
